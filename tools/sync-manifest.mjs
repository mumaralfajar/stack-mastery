// Auto-generates src/data/manifest.ts and syncs curriculum/interview summary counts in README.md.
// Usage: node tools/sync-manifest.mjs [--check]
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { ID_CORE_TRACKS } from '../src/data/id/core.ts';
import { ID_WEB_TRACKS } from '../src/data/id/web.ts';
import { loadInterviewData } from '../src/data/index.ts';
import { CORE_TRACKS } from '../src/data/tracks-core.ts';
import { UI_TRACKS } from '../src/data/tracks-ui.ts';
import { VIZ_IDS } from '../src/scripts/viz/registry.ts';

const ROOT = fileURLToPath(new URL('..', import.meta.url));
const MANIFEST_PATH = resolve(ROOT, 'src/data/manifest.ts');
const README_PATH = resolve(ROOT, 'README.md');
const PRODUCT_PATH = resolve(ROOT, 'PRODUCT.md');

export async function computeCurriculumStats() {
  const tracks = [...CORE_TRACKS, ...UI_TRACKS];
  const IV = await loadInterviewData();
  const idById = Object.fromEntries([...ID_CORE_TRACKS, ...ID_WEB_TRACKS].map((t) => [t.id, t]));
  const flatLessons = tracks.flatMap((t) =>
    t.lessons.map((l) => ({
      trackId: t.id,
      id: l.id,
      level: l.level,
      mins: l.mins,
      ...(l.viz ? { viz: l.viz } : {}),
      quizIds: l.quiz.map((q) => q.id),
    })),
  );
  const trackMeta = tracks.map((t) => ({
    id: t.id,
    name: t.name,
    lang: t.lang,
    tagline: t.tagline,
    taglineId: idById[t.id]?.tagline ?? t.tagline,
    verifiedAgainst: t.verifiedAgainst,
    verifiedDate: t.verifiedDate,
    lessonCount: t.lessons.length,
  }));
  const interviewTotals = {
    problems: IV.problems.length,
    cases: IV.design.cases.length,
    behavioralThemes: IV.behavioral.length,
    rapidTotal: IV.rapid.reduce((a, r) => a + r.qs.length, 0),
    maxMocks: 8,
  };
  const stats = {
    tracksCount: tracks.length,
    tracks,
    lessons: flatLessons.length,
    quizCount: flatLessons.reduce((a, l) => a + l.quizIds.length, 0),
    labs: VIZ_IDS.length,
    predictCount: tracks.reduce((a, t) => a + t.lessons.filter((l) => l.predict).length, 0),
    splitCount: tracks.reduce((a, t) => a + t.lessons.filter((l) => l.splits?.length).length, 0),
    problems: interviewTotals.problems,
    patterns: IV.patterns.length,
    cases: interviewTotals.cases,
    behThemes: interviewTotals.behavioralThemes,
    behQs: IV.behavioral.reduce((a, b) => a + b.qs.length, 0),
    rapidTotal: interviewTotals.rapidTotal,
    uiPrompts: IV.ui.length,
    maxMocks: interviewTotals.maxMocks,
  };
  return { trackMeta, flatLessons, interviewTotals, stats };
}

export function renderManifestSource(data) {
  const { trackMeta, flatLessons, interviewTotals } = data;
  const lessonsBlock = flatLessons
    .map((entry) => {
      const lines = [
        '  {',
        `    "trackId": ${JSON.stringify(entry.trackId)},`,
        `    "id": ${JSON.stringify(entry.id)},`,
        `    "level": ${entry.level},`,
        `    "mins": ${entry.mins},`,
      ];
      if (entry.viz) lines.push(`    "viz": ${JSON.stringify(entry.viz)},`);
      lines.push(`    "quizIds": ${JSON.stringify(entry.quizIds)}`);
      lines.push('  }');
      return lines.join('\n');
    })
    .join(',\n');

  return `// AUTO-GENERATED by tools/sync-manifest.mjs — do not edit by hand.
// Lightweight curriculum & interview manifest (zero lesson prose).
import type { InterviewTotals, LessonIndexEntry, TrackMeta } from '../lib/types.ts';

export const LEVELS_EN: readonly [string, string, string, string] = [
  'Beginner',
  'Intermediate',
  'Advanced',
  'Expert',
];

export const LEVELS_ID: readonly [string, string, string, string] = [
  'Pemula',
  'Menengah',
  'Mahir',
  'Expert',
];

export const TRACK_META: readonly TrackMeta[] = ${JSON.stringify(trackMeta, null, 2)};

export const LESSON_INDEX: readonly LessonIndexEntry[] = [
${lessonsBlock}
];

export const INTERVIEW_TOTALS: InterviewTotals = {
  problems: ${interviewTotals.problems},
  cases: ${interviewTotals.cases},
  behavioralThemes: ${interviewTotals.behavioralThemes},
  rapidTotal: ${interviewTotals.rapidTotal},
  maxMocks: ${interviewTotals.maxMocks},
};
`;
}

export function syncReadmeText(text, stats) {
  let out = text
    .replace(/^(### [A-Za-z]+ tracks, )\d+( lessons, four levels each)$/m, `$1${stats.lessons}$2`)
    .replace(/(across )\d+( lessons\))/g, `$1${stats.predictCount}$2`)
    .replace(/(code tabs\*\* \()\d+( lessons across )\d+( tracks\))/g, `$1${stats.splitCount}$2${stats.tracksCount}$3`)
    .replace(/(\| \*\*Interactive diagrams\*\* \| )\d+( live widgets)/g, `$1${stats.labs}$2`)
    .replace(/(\| \*\*Flashcard review\*\* \| )\d+( quiz questions)/g, `$1${stats.quizCount}$2`)
    .replace(/(\| \*\*Coding\*\* \| )\d+( classic problems across )\d+( patterns)/g, `$1${stats.problems}$2${stats.patterns}$3`)
    .replace(/(\| \*\*System design\*\* \| 45-minute framework, )\d+( worked cases)/g, `$1${stats.cases}$2`)
    .replace(/(\| \*\*Behavioral\*\* \| STAR \+ Reflection method, )\d+( questions across )\d+( themes)/g, `$1${stats.behQs}$2${stats.behThemes}$3`)
    .replace(/(\| \*\*Rapid-fire\*\* \| )\d+( stack questions)/g, `$1${stats.rapidTotal}$2`)
    .replace(/(\band )\d+( UI component prompts)/g, `$1${stats.uiPrompts}$2`)
    .replace(/(The interface, )\d+( lessons, quizzes)/g, `$1${stats.lessons}$2`)
    .replace(/(A lesson \()\d+( lessons\))/g, `$1${stats.lessons}$2`)
    .replace(/(each of the )\d+( labs \|)/g, `$1${stats.labs}$2`)
    .replace(/(\| `src\/scripts\/viz\/` \| )\d+( interactive labs;)/g, `$1${stats.labs}$2`)
    .replace(/(\| `[^`]+` \| `LESSON_INDEX` \()\d+( lessons\))/g, `$1${stats.lessons}$2`);

  for (const t of stats.tracks) {
    const escName = t.name.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
    out = out.replace(new RegExp(`(\\| \\*\\*${escName}\\*\\* \\| )\\d+( \\|)`), `$1${t.lessons.length}$2`);
  }
  return out;
}

function syncProductText(text, stats) {
  return text
    .replace(/(\bruntime code, |runnable code, )\d+( interactive visual simulations)/g, `$1${stats.labs}$2`)
    .replace(
      /(- \*\*Scale:\*\* )\d+( tracks, )\d+( lessons, )\d+( interactive visual labs, 4 browser playgrounds, )\d+( spaced-repetition quiz flashcards, )\d+( coding interview problems, )\d+( worked system design cases, )\d+( rapid-fire Q&As)/g,
      `$1${stats.tracksCount}$2${stats.lessons}$3${stats.labs}$4${stats.quizCount}$5${stats.problems}$6${stats.cases}$7${stats.rapidTotal}$8`,
    );
}

export async function checkManifestSync({ write = false } = {}) {
  const data = await computeCurriculumStats();
  const nextManifest = renderManifestSource(data);
  const curManifest = readFileSync(MANIFEST_PATH, 'utf8');
  const nextReadme = syncReadmeText(readFileSync(README_PATH, 'utf8'), data.stats);
  const curReadme = readFileSync(README_PATH, 'utf8');
  const stale = [];

  if (curManifest !== nextManifest) {
    stale.push('src/data/manifest.ts');
    if (write) writeFileSync(MANIFEST_PATH, nextManifest, 'utf8');
  }
  if (curReadme !== nextReadme) {
    stale.push('README.md');
    if (write) writeFileSync(README_PATH, nextReadme, 'utf8');
  }
  // PRODUCT.md is gitignored (local-only spec); keep it aligned locally on write without failing CI.
  if (write && existsSync(PRODUCT_PATH)) {
    const curProduct = readFileSync(PRODUCT_PATH, 'utf8');
    const nextProduct = syncProductText(curProduct, data.stats);
    if (curProduct !== nextProduct) writeFileSync(PRODUCT_PATH, nextProduct, 'utf8');
  }
  return { ok: stale.length === 0, stale, stats: data.stats };
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const checkOnly = process.argv.includes('--check');
  const res = await checkManifestSync({ write: !checkOnly });
  if (checkOnly) {
    if (!res.ok) {
      console.error(`Out of sync: ${res.stale.join(', ')}. Run \`bun run sync:manifest\` to update.`);
      process.exit(1);
    }
    console.log(`Manifest and README counts are in sync (${res.stats.tracksCount} tracks, ${res.stats.lessons} lessons, ${res.stats.quizCount} quiz items, ${res.stats.labs} labs).`);
  } else {
    console.log(
      res.stale.length
        ? `Updated ${res.stale.join(', ')} (${res.stats.tracksCount} tracks, ${res.stats.lessons} lessons, ${res.stats.quizCount} quiz items, ${res.stats.labs} labs).`
        : 'Manifest and README are already up to date.',
    );
  }
}
